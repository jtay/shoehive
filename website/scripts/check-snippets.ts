// Fails when any TypeScript shown on the site does not type-check. It checks, in one
// TypeScript program with the settings of website/snippets/tsconfig.json (strict, with
// `shoehive` and `shoehive/*` mapped to packages/shoehive/src):
//
// 1. every file under website/snippets/ (shown on pages with <Snippet>);
// 2. every fenced ts/tsx block in the site's hand-written pages and in docs/reference/*.md,
//    each as its own module, unless its fence says `nocheck` (```ts nocheck);
// 3. every <Snippet file="..." region="..."> reference: the file must exist under an allowed
//    root and the region must exist.
//
// Errors are reported as file:line:column of the page (or snippet file), so they can be
// fixed where they are written. Generated pages (synced ADRs and RFCs, TypeDoc output) are
// not checked: the ADRs and the RFC are historical design records.

import { readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import ts from 'typescript';
import { contentDir, listFiles, repoRoot, websiteDir } from '../src/lib/pages';
import { readSnippet, SnippetError } from '../src/lib/snippets';

const CHECKED_LANGS = new Set(['ts', 'tsx', 'typescript', 'mts', 'cts']);
const GENERATED_MARKER = '<!-- Generated by website/scripts/sync-docs.ts';
const snippetsDir = join(websiteDir, 'snippets');
const inlineDir = join(snippetsDir, '.inline');

interface Block {
  source: string; // repository-relative path of the page
  line: number; // 1-based line of the first code line
  lang: string;
  code: string;
}

interface Problem {
  file: string;
  line: number;
  column: number;
  message: string;
}

const problems: Problem[] = [];

/** Fenced code blocks of a markdown or MDX file, with their position. */
function fencedBlocks(text: string, source: string): (Block & { meta: string })[] {
  const lines = text.split(/\r?\n/);
  const blocks: (Block & { meta: string })[] = [];
  for (let i = 0; i < lines.length; i++) {
    const open = /^(\s*)(`{3,}|~{3,})\s*([\w+-]*)\s*(.*)$/.exec(lines[i] ?? '');
    if (!open) continue;
    const [, indent = '', fence = '', lang = '', meta = ''] = open;
    const body: string[] = [];
    let j = i + 1;
    for (; j < lines.length; j++) {
      const line = lines[j] ?? '';
      const close = /^\s*(`{3,}|~{3,})\s*$/.exec(line)?.[1];
      if (close?.[0] === fence[0] && (close?.length ?? 0) >= fence.length) break;
      body.push(line.startsWith(indent) ? line.slice(indent.length) : line.trimStart());
    }
    blocks.push({ source, line: i + 2, lang: lang.toLowerCase(), meta, code: body.join('\n') });
    i = j;
  }
  return blocks;
}

function attribute(tag: string, name: string): string | undefined {
  return new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1];
}

function lineOf(text: string, index: number): number {
  return text.slice(0, index).split('\n').length;
}

// --- Collect pages ---------------------------------------------------------------------

const pages = [
  ...listFiles(contentDir, ['.md', '.mdx']).filter(
    (path) => !relative(contentDir, path).startsWith('reference/api/'),
  ),
  ...listFiles(join(repoRoot, 'docs/reference'), ['.md']),
];

const inline: Block[] = [];
let skipped = 0;
let snippetRefs = 0;

for (const path of pages) {
  const text = readFileSync(path, 'utf8');
  if (text.includes(GENERATED_MARKER)) continue;
  const source = relative(repoRoot, path);

  for (const block of fencedBlocks(text, source)) {
    if (!CHECKED_LANGS.has(block.lang)) continue;
    if (/(?:^|\s)nocheck(?:\s|$)/.test(block.meta)) {
      skipped++;
      continue;
    }
    inline.push(block);
  }

  for (const match of text.matchAll(/<Snippet\s[^>]*?\/?>/gs)) {
    snippetRefs++;
    const tag = match[0];
    const line = lineOf(text, match.index);
    const file = attribute(tag, 'file');
    if (file === undefined) {
      problems.push({ file: source, line, column: 1, message: '<Snippet> needs file="..."' });
      continue;
    }
    try {
      readSnippet(repoRoot, file, attribute(tag, 'region'));
    } catch (error) {
      if (!(error instanceof SnippetError)) throw error;
      problems.push({ file: source, line, column: 1, message: error.message });
    }
  }

  for (const match of text.matchAll(/<Code\b[^>]*\blang=["'{]+(ts|tsx|typescript)\b/g)) {
    problems.push({
      file: source,
      line: lineOf(text, match.index),
      column: 1,
      message: 'TypeScript in <Code> is not type-checked: use <Snippet> or a fenced block',
    });
  }
}

// --- Type-check snippet files and inline blocks in one program -------------------------

const configPath = join(snippetsDir, 'tsconfig.json');
const config = ts.getParsedCommandLineOfConfigFile(
  configPath,
  {},
  {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => {
      throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
    },
  },
);
if (!config) throw new Error(`Could not read ${configPath}`);

const virtual = new Map<string, Block>();
inline.forEach((block, i) => {
  const ext = block.lang === 'tsx' ? 'tsx' : 'ts';
  const name = `${block.source.replace(/[^\w]+/g, '_')}_L${String(block.line)}_${String(i)}.${ext}`;
  virtual.set(join(inlineDir, name), block);
});

const base = ts.createCompilerHost(config.options);
const host: ts.CompilerHost = {
  ...base,
  fileExists: (file) => virtual.has(file) || base.fileExists(file),
  readFile: (file) => virtual.get(file)?.code ?? base.readFile(file),
  getSourceFile: (file, languageVersion, onError, shouldCreate) => {
    const block = virtual.get(file);
    return block
      ? ts.createSourceFile(file, block.code, languageVersion, true)
      : base.getSourceFile(file, languageVersion, onError, shouldCreate);
  },
};

const snippetFiles = config.fileNames.filter((f) => !f.startsWith(inlineDir));
const program = ts.createProgram({
  rootNames: [...snippetFiles, ...virtual.keys()],
  options: config.options,
  host,
});

const ownFiles = new Set([...snippetFiles, ...virtual.keys()]);
const diagnostics = [
  ...program.getOptionsDiagnostics(),
  ...program.getGlobalDiagnostics(),
  ...program
    .getSourceFiles()
    .filter((sf) => ownFiles.has(sf.fileName))
    .flatMap((sf) => [
      ...program.getSyntacticDiagnostics(sf),
      ...program.getSemanticDiagnostics(sf),
    ]),
];

for (const d of diagnostics) {
  const message = ts.flattenDiagnosticMessageText(d.messageText, '\n');
  if (!d.file || d.start === undefined) {
    problems.push({ file: relative(repoRoot, configPath), line: 1, column: 1, message });
    continue;
  }
  const pos = d.file.getLineAndCharacterOfPosition(d.start);
  const block = virtual.get(d.file.fileName);
  if (block) {
    problems.push({
      file: block.source,
      line: block.line + pos.line,
      column: pos.character + 1,
      message: `${message} (in a \`\`\`${block.lang} block; add "nocheck" to the fence only if it is not meant to compile)`,
    });
  } else {
    problems.push({
      file: relative(repoRoot, d.file.fileName),
      line: pos.line + 1,
      column: pos.character + 1,
      message,
    });
  }
}

// --- Report -----------------------------------------------------------------------------

const summary = `${String(snippetFiles.length)} snippet files, ${String(inline.length)} inline blocks (${String(skipped)} marked nocheck), ${String(snippetRefs)} <Snippet> references`;

if (problems.length > 0) {
  for (const p of problems) {
    console.error(`${p.file}:${String(p.line)}:${String(p.column)}: ${p.message}`);
  }
  console.error(`\ncheck-snippets: ${String(problems.length)} problem(s) in ${summary}.`);
  process.exit(1);
}
console.log(`check-snippets: OK. ${summary}.`);
