function changelogPage(): string {
  const changesetDir = join(repoRoot, '.changeset');
  const pending = readdirSync(changesetDir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md')
    .sort()
    .map((f) => {
      const text = readFileSync(join(changesetDir, f), 'utf8');
      const fm = /^---\n([\s\S]*?)\n---\n/.exec(text);
      const bumps = (fm?.[1] ?? '')
        .split('\n')
        .map((l) => /^['"]?([^'":]+)['"]?:\s*(\w+)/.exec(l))
        .filter((m): m is RegExpExecArray => m !== null)
        .map((m) => `${m[1] ?? ''} (${m[2] ?? ''})`);
      const body = text
        .slice(fm?.[0].length ?? 0)
        .trim()
        .replace(/\s+/g, ' ');
      return `- ${body} _${bumps.join(', ')}_`;
    });
  const changelogPath = 'packages/shoehive/CHANGELOG.md';
  const released = existsSync(join(repoRoot, changelogPath))
    ? splitTitle(read(changelogPath), changelogPath).body.replace(/^## /gm, '### ')
    : 'No release yet. The first release will be `1.0.0-next.0` on the `next` dist-tag.';
  return [
    frontmatter({
      title: 'Changelog',
      description: 'What changed in each release of shoehive, and what is waiting to be released.',
      editUrl: false,
    }),
    HEADER(`.changeset/*.md and ${changelogPath}`),
    '',
    '## Unreleased',
    '',
    pending.length ? 'Changesets merged to `main` and waiting for the next release:' : 'Nothing.',
    '',
    ...pending,
    '',
    '## Released',
    '',
    released,
    '',
  ].join('\n');
}

// ---------------------------------------------------------------------------------------
// Run

const pages = syncedPages();
for (const page of pages) siteUrls.set(page.source, page.url);
for (const page of pages) outputs.set(page.out, renderSyncedPage(page));
outputs.set('reference/config.md', configPage());
outputs.set('reference/error-codes.md', errorCodesPage());
outputs.set('reference/changelog.md', changelogPage());

if (errors.length > 0) {
  console.error(`sync-docs: ${String(errors.length)} problem(s):`);
  for (const error of errors) console.error(`  ${error}`);
  process.exit(1);
}

if (CHECK) {
  console.log(`sync-docs --check: ${String(outputs.size)} generated pages are consistent.`);
  process.exit(0);
}

// Generated directories are owned by this script (the TypeDoc output under reference/api is
// owned by starlight-typedoc and regenerated by every build).
