const EDIT = `${GITHUB}/edit/main`;
const HEADER = (source: string) =>
  `<!-- Generated by website/scripts/sync-docs.ts from ${source}. Edit the source, not this file. -->`;

const errors: string[] = [];
const outputs = new Map<string, string>();

function fail(message: string): void {
  errors.push(message);
}

function read(path: string): string {
  return readFileSync(join(repoRoot, path), 'utf8');
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

type Scalar = string | number | boolean;

function frontmatter(data: Record<string, Scalar | Record<string, Scalar> | undefined>): string {
  const lines = ['---'];
  for (const [key, value] of Object.entries(data)) {
    if (value === undefined) continue;
    if (typeof value === 'object') {
      lines.push(`${key}:`);
      for (const [k, v] of Object.entries(value)) {
        lines.push(`  ${k}: ${typeof v === 'string' ? yamlString(v) : String(v)}`);
      }
    } else {
      lines.push(`${key}: ${typeof value === 'string' ? yamlString(value) : String(value)}`);
    }
  }
  lines.push('---', '');
  return lines.join('\n');
}

