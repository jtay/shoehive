// Builds the generated part of the site's content from the repository, so every fact has one
// source:
//
//   docs/reference/*.md         -> src/content/docs/reference/<name>.md   (protocol, stores, ...)
//   docs/adr/*.md               -> src/content/docs/contributing/adr/
//   docs/rfc/*.md               -> src/content/docs/contributing/rfc/
//   packages/shoehive/src/...   -> reference/config.md, reference/error-codes.md
//   .changeset/, CHANGELOG.md   -> reference/changelog.md
//   docs/favicon/*              -> public/favicon/, src/assets/logo.png
//
// Relative links between those files are rewritten to site URLs (or to GitHub for files that
// are not on the site). Generated files are gitignored. `--check` generates everything in
// memory and runs the consistency checks without writing (used by `pnpm docs:check`).

