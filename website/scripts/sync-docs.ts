// Reading the package source with the TypeScript parser (no execution, no build needed)

function parse(path: string): ts.SourceFile {
  return ts.createSourceFile(path, read(path), ts.ScriptTarget.Latest, true);
}

function findNode<T extends ts.Node>(
  sf: ts.SourceFile,
  test: (node: ts.Node) => node is T,
  what: string,
): T | undefined {
  let found: T | undefined;
  const visit = (node: ts.Node): void => {
    if (found) return;
    if (test(node)) found = node;
    else ts.forEachChild(node, visit);
  };
  visit(sf);
  if (!found) fail(`${sf.fileName}: could not find ${what}`);
  return found;
}

/** The string literals of `export const NAME = [...] as const`. */
function stringArray(path: string, name: string): string[] {
  const sf = parse(path);
  const decl = findNode(
    sf,
    (n): n is ts.VariableDeclaration =>
      ts.isVariableDeclaration(n) && ts.isIdentifier(n.name) && n.name.text === name,
    `const ${name}`,
  );
  let init = decl?.initializer;
  while (init && (ts.isAsExpression(init) || ts.isSatisfiesExpression(init))) {
    init = init.expression;
  }
  if (!init || !ts.isArrayLiteralExpression(init)) {
    fail(`${path}: ${name} is not an array literal`);
    return [];
  }
  return init.elements.filter(ts.isStringLiteral).map((e) => e.text);
}

/** The numeric properties of `export const NAME = { KEY: 1000, ... } as const`. */
function numberRecord(path: string, name: string): Map<number, string> {
  const sf = parse(path);
  const decl = findNode(
    sf,
    (n): n is ts.VariableDeclaration =>
      ts.isVariableDeclaration(n) && ts.isIdentifier(n.name) && n.name.text === name,
    `const ${name}`,
  );
  let init = decl?.initializer;
  while (init && ts.isAsExpression(init)) init = init.expression;
  const out = new Map<number, string>();
  if (init && ts.isObjectLiteralExpression(init)) {
    for (const prop of init.properties) {
      if (ts.isPropertyAssignment(prop) && ts.isNumericLiteral(prop.initializer)) {
        out.set(Number(prop.initializer.text), prop.name.getText(sf));
      }
    }
  }
  return out;
}

function docComment(node: ts.Node): string {
  const parts = ts
    .getJSDocCommentsAndTags(node)
    .filter(ts.isJSDoc)
    .map((doc) => ts.getTextOfJSDocComment(doc.comment) ?? '');
  return parts.join(' ').replace(/\s+/g, ' ').trim();
}

interface OptionRow {
  name: string;
  type: string;
  required: boolean;
  default: string;
  description: string;
}

/** Splits "Does X. Default `y`." into the description and the default value. */
function splitDefault(comment: string): { description: string; default?: string } {
  const onOff = /\b(On|Off) by default\b/.exec(comment);
  if (onOff?.[1]) return { description: comment, default: onOff[1].toLowerCase() };
  const start = /(?:^|\s)Defaults?(?: to)?:?\s+/.exec(comment);
  if (!start) return { description: comment };
  let i = start.index + start[0].length;
  let inCode = false;
  for (; i < comment.length; i++) {
    const c = comment[i];
    if (c === '`') inCode = !inCode;
    if (!inCode && (c === '.' || c === ';' || c === ':') && /\s|$/.test(comment[i + 1] ?? '')) {
      break;
    }
  }
  const value = comment.slice(start.index + start[0].length, i).trim();
  const endsSentence = comment[i] === '.' || i >= comment.length;
  const description = endsSentence
    ? (comment.slice(0, start.index) + comment.slice(i + 1)).replace(/\s+/g, ' ').trim()
    : comment;
  return { description, default: value };
}

function optionRows(
  members: ts.NodeArray<ts.TypeElement>,
  sf: ts.SourceFile,
  owner: string,
  fallbacks: Record<string, string> = {},
): OptionRow[] {
  return members.filter(ts.isPropertySignature).map((member) => {
    const name = member.name.getText(sf);
    const doc = docComment(member);
    const comment = doc === '' ? (fallbacks[name] ?? '') : doc;
    if (!comment) fail(`${owner}.${name} has no doc comment: add one (or a fallback in sync-docs)`);
    const { description, default: def } = splitDefault(comment);
    return {
      name,
      type: (member.type?.getText(sf) ?? 'unknown').replace(/\s+/g, ' '),
      required: !member.questionToken,
      default: def ?? '',
      description,
    };
  });
}

function interfaceRows(
  path: string,
  name: string,
  fallbacks?: Record<string, string>,
): OptionRow[] {
  const sf = parse(path);
  const decl = findNode(
    sf,
    (n): n is ts.InterfaceDeclaration => ts.isInterfaceDeclaration(n) && n.name.text === name,
    `interface ${name}`,
  );
  return decl ? optionRows(decl.members, sf, name, fallbacks) : [];
}

const cell = (text: string) => text.replace(/\|/g, '\\|');
const code = (text: string) => (text.includes('`') ? text : `\`${text}\``);

function optionsTable(rows: OptionRow[]): string {
  const lines = ['| Option | Type | Default | Description |', '| --- | --- | --- | --- |'];
  for (const row of rows) {
    const def = row.required ? 'required' : row.default ? cell(row.default) : '';
    lines.push(`| \`${row.name}\` | ${cell(code(row.type))} | ${def} | ${cell(row.description)} |`);
  }
  return lines.join('\n');
}

