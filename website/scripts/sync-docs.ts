interface SyncedPage {
  source: string;
  out: string;
  url: string;
  description?: string;
  sidebar?: { label?: string; order?: number };
  title?: (title: string) => string;
  note?: string;
}

const REFERENCE_DESCRIPTIONS: Record<string, string> = {
  protocol:
    'The Shoehive wire protocol, version 1: messages, synced documents, errors, close codes and limits.',
  stores: 'Store adapters for memory, SQLite, Postgres and Redis, and how to write your own.',
  devtools: 'The devtools inspector: turning it on safely, time travel, forks and fixtures.',
  benchmarks: 'How fast the engine is, what is measured and how to run the benchmark.',
};

const REFERENCE_LABELS: Record<string, string> = {
  protocol: 'Wire protocol',
  benchmarks: 'Benchmarks',
};

function syncedPages(): SyncedPage[] {
  const pages: SyncedPage[] = [];
  const md = (dir: string) =>
    readdirSync(join(repoRoot, dir))
      .filter((f) => f.endsWith('.md'))
      .sort();

  for (const file of md('docs/reference')) {
    const name = basename(file, '.md');
    const page: SyncedPage = {
      source: `docs/reference/${file}`,
      out: `reference/${name}.md`,
      url: `/reference/${name}/`,
    };
    const description = REFERENCE_DESCRIPTIONS[name];
    if (description) page.description = description;
    const label = REFERENCE_LABELS[name];
    if (label) page.sidebar = { label };
    pages.push(page);
  }
  for (const file of md('docs/adr')) {
    if (file === 'template.md') continue;
    const name = basename(file, '.md');
    if (file === 'README.md') {
      pages.push({
        source: `docs/adr/${file}`,
        out: 'contributing/adr/index.md',
        url: '/contributing/adr/',
        sidebar: { label: 'ADR index', order: 0 },
        title: () => 'Architecture decision records',
        description: 'Every architecture decision behind Shoehive, and how to propose one.',
      });
    } else {
      pages.push({
        source: `docs/adr/${file}`,
        out: `contributing/adr/${name}.md`,
        url: `/contributing/adr/${name}/`,
        sidebar: { order: Number.parseInt(name, 10) || 999 },
        note: DESIGN_NOTE,
      });
    }
  }
  for (const file of md('docs/rfc')) {
    const name = basename(file, '.md');
    pages.push({
      source: `docs/rfc/${file}`,
      out: `contributing/rfc/${name}.md`,
      url: `/contributing/rfc/${name}/`,
      note: DESIGN_NOTE.replace('decision record', 'plan'),
    });
  }
  return pages;
}

function renderSyncedPage(page: SyncedPage): string {
  const markdown = read(page.source);
  const split = splitTitle(markdown, page.source);
  const title = page.title ? page.title(split.title) : split.title;
  const body = rewriteLinks(split.body, page.source);
  const label = page.sidebar?.label ?? /^ADR \d+: (.+)$/.exec(title)?.[1] ?? undefined;
  return [
    frontmatter({
      title,
      description: page.description ?? firstSentence(split.body),
      editUrl: `${EDIT}/${page.source}`,
      sidebar:
        page.sidebar || label
          ? {
              ...(label ? { label } : {}),
              ...(page.sidebar?.order === undefined ? {} : { order: page.sidebar.order }),
            }
          : undefined,
    }),
    HEADER(page.source),
    '',
    ...(page.note ? [page.note, ''] : []),
    body,
  ].join('\n');
}

