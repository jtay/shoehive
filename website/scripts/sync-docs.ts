/** Rows of the first markdown table after `heading` in `markdown`. */
function tableAfter(markdown: string, heading: string, file: string): string[][] {
  const start = markdown.indexOf(heading);
  if (start === -1) {
    fail(`${file}: no heading "${heading}"`);
    return [];
  }
  const lines = markdown.slice(start).split('\n');
  const first = lines.findIndex((l) => l.startsWith('|'));
  const rows: string[][] = [];
  for (let i = first + 2; i < lines.length && lines[i]?.startsWith('|'); i++) {
    rows.push(
      (lines[i] ?? '')
        .slice(1, -1)
        .split(/(?<!\\)\|/)
        .map((c) => c.trim()),
    );
  }
  return rows;
}

const unquote = (c: string) => c.replace(/^`|`$/g, '');

function compareSets(what: string, inCode: string[], inSpec: string[]): void {
  const missing = inCode.filter((c) => !inSpec.includes(c));
  const extra = inSpec.filter((c) => !inCode.includes(c));
  if (missing.length) fail(`${what}: in the code but not in protocol.md: ${missing.join(', ')}`);
  if (extra.length) fail(`${what}: in protocol.md but not in the code: ${extra.join(', ')}`);
}

function errorCodesPage(): string {
  const spec = 'docs/reference/protocol.md';
  const protocol = read(spec);
  const errorsTs = 'packages/shoehive/src/core/errors.ts';
  const builtin = stringArray(errorsTs, 'BUILTIN_ERROR_CODES');
  const clientCodes = stringArray('packages/shoehive/src/client/client.ts', 'CLIENT_ERROR_CODES');
  const close = numberRecord('packages/shoehive/src/protocol/messages.ts', 'CLOSE');
  const gameCode = /const GAME_CODE = \/(.+)\/;/.exec(read(errorsTs))?.[1];
  if (!gameCode) fail(`${errorsTs}: could not find GAME_CODE`);

  const builtinRows = tableAfter(protocol, '## 7. Errors', spec);
  const clientRows = tableAfter(protocol, '### 7.1 Codes raised by the client', spec);
  const closeRows = tableAfter(protocol, '## 8. Close codes', spec);
  compareSets(
    'Built-in error codes',
    builtin,
    builtinRows.map((r) => unquote(r[0] ?? '')),
  );
  compareSets(
    'Client error codes',
    clientCodes,
    clientRows.map((r) => unquote(r[0] ?? '')),
  );
  compareSets(
    'Close codes',
    [...close.keys()].map(String),
    closeRows.map((r) => r[0] ?? ''),
  );

  const byCode = new Map(builtinRows.map((r) => [unquote(r[0] ?? ''), r]));
  const clientByCode = new Map(clientRows.map((r) => [unquote(r[0] ?? ''), r]));

  return [
    frontmatter({
      title: 'Error codes',
      description:
        'Every error code Shoehive sends or raises, checked against the source on every build.',
      editUrl: `${EDIT}/${spec}`,
    }),
    HEADER(`${spec} sections 7 and 8, checked against ${errorsTs} and the client`),
    '',
    'Every failed request rejects with a `ShoehiveError`. Its `source` is `"shoehive"` for the',
    'codes on this page and `"game"` for codes your game raised with `reject()`. The lists are',
    'read from the source code; the descriptions come from the',
    '[wire protocol](/reference/protocol/#7-errors), and the build fails if the two disagree.',
    '',
    '## Codes the server sends',
    '',
    '| Code | When | `details` |',
    '| --- | --- | --- |',
    ...builtin.map((c) => {
      const row = byCode.get(c);
      return `| \`${c}\` | ${row?.[1] ?? ''} | ${row?.[2] ?? ''} |`;
    }),
    '',
    '## Codes the client raises',
    '',
    '`shoehive/client` raises these locally. Servers never send them.',
    '',
    '| Code | When |',
    '| --- | --- |',
    ...clientCodes.map((c) => `| \`${c}\` | ${clientByCode.get(c)?.[1] ?? ''} |`),
    '',
    '## Game codes',
    '',
    `Codes passed to \`reject(code, details?)\` must match \`/${gameCode ?? ''}/\` and must not`,
    'reuse a code above. Reusing one is a type error, and a runtime error if types are bypassed.',
    '',
    '## Close codes',
    '',
    '| Code | Meaning | Client should |',
    '| --- | --- | --- |',
    ...closeRows.map((r) => `| ${r[0] ?? ''} | ${r[1] ?? ''} | ${r[2] ?? ''} |`),
    '',
  ].join('\n');
}

